const tables = { vi: vi as Table, en, ja } as const;

export type Ft = (key: FtKey, vars?: Record<string, string | number>) => string;

/** Translator for the flashcard pages, following the interface language. */
export function useFt(): Ft {
  const { uiLang } = useUiLanguage();
  return useCallback<Ft>(
    (key, vars) => {
      const text = (tables[uiLang] ?? tables.vi)[key] ?? tables.vi[key];
      return (vars ? fmt(text, vars) : text).normalize("NFC");
    },
    [uiLang],
  );
}
